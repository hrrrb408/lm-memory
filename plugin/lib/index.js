function writeServerShim(config) {
  let tempPath;
  try {
    const realServer = ["../../server/memory-server.mjs", "../../../server/memory-server.mjs"]
      .map((r) => path.join(libDir(), r)).find((p) => fs.existsSync(p));
    if (!realServer) { log("server shim skipped: memory-server.mjs not found"); return null; }
    const binDir = path.resolve(MEM_DIR, "bin");
    fs.mkdirSync(binDir, { recursive: true });
    const shimPath = path.join(binDir, "lm-memory-server.mjs");
    const content = [
      "#!/usr/bin/env node",
      "// Auto-generated by dsh-lm-memory plugin — rewritten at every host start. Do not edit.",
      "// MCP uses this stable launcher; the absolute server path comes from the installed plugin.",
      'import { pathToFileURL } from "node:url";',
      // v0.15.1 系统级禁外发：allowRemote:false 经 shim 传给 server（冲突复核/孤儿回收遵守）
      ...(config?.allowRemote === false ? ['process.env.LM_REMOTE_DISABLED = "1"; // 插件 allowRemote:false → 系统级禁外发'] : []),
      `await import(pathToFileURL(${JSON.stringify(realServer)}).href);`,
      "",
    ].join("\n");
    tempPath = shimPath + "." + randomUUID() + ".tmp";
    fs.writeFileSync(tempPath, content, { flag: "wx" });
    fs.renameSync(tempPath, shimPath);
    tempPath = null;
    log("server shim written: " + shimPath);
    return shimPath;
  } catch (e) {
    log("shim write error: " + (e?.message ?? e));
    return null;
  } finally {
    if (tempPath) { try { fs.rmSync(tempPath, { force: true }); } catch {} }
  }
}

// ===== viewer 旧版自动升级（v0.10）=====
// 病灶：viewer 是 detached 进程，DSH app 重启杀不掉它；旧 viewer 占着端口且它 spawn 的
// MCP server 子进程也是旧代码（无 announce）→ 管理页写操作永远不进变更热流。
// 探测 /api/version 中的版本和启动配置标识；只替换 OS 确认由此安装启动的进程。
// 无法确认归属的 listener 保持原样，不把其地址发给设置面板。
const execFileSyncSafe = (cmd, args) => { try { return execFileSync(cmd, args, { encoding: "utf8", timeout: 3000 }).trim(); } catch { return ""; } };
function pkgVersion() {
  try { return JSON.parse(fs.readFileSync(path.join(libDir(), "../../package.json"), "utf8")).version || "0.0.0"; } catch { return "0.0.0"; }
}
function canReplaceVersion(installed, wanted) {
  if (installed === wanted) return true;
  const [a, preA] = installed.split("-", 2), [b, preB] = wanted.split("-", 2);
  const pa = a.split(".").map(Number), pb = b.split(".").map(Number);
  for (let i = 0; i < 3; i++) { if (pa[i] !== pb[i]) return pa[i] < pb[i]; }
  // Do not guess the ordering of distinct prerelease labels.
  return Boolean(preA && !preB);
}
async function probeViewer(port) {
  try {
    const r = await fetch(`http://127.0.0.1:${port}/api/version`, { signal: AbortSignal.timeout(1500), redirect: "error" });
    if (r.ok) {
      const remote = await r.json();
      if (typeof remote?.version === "string" && /^\d+\.\d+\.\d+(?:-[\w.-]+)?$/.test(remote.version)) return remote;
    }
  } catch {}
  return null;
}
function matchesViewer(remote, want) {
  return remote?.version === want.version && remote.startupKey === want.startupKey;
}

async function ensureFreshViewer(port, node, viewerPath, want) {
  const remote = await probeViewer(port);
  if (matchesViewer(remote, want)) return false;
  const listener = () => execFileSyncSafe("lsof", ["-a", "-ti4TCP:" + port, "-sTCP:LISTEN"])
    .split("\n").map(Number).filter((n) => Number.isSafeInteger(n) && n > 1);
  const listeners = listener();
  if (!remote && !listeners.length) return true;
  const [pid] = listeners;
  // The loopback response is not proof of ownership. Require the real listener and
  // exactly our executable, installed script, port, and managed-launch marker.
  const command = [node, ...viewerArgs(viewerPath, port)].join(" ");
  if (listeners.length === 1 && remote?.pid === pid && typeof remote.startupKey === "string"
      && canReplaceVersion(remote.version, want.version)
      && execFileSyncSafe("ps", ["-ww", "-p", String(pid), "-o", "command="]) === command) {
    try { process.kill(pid, "SIGTERM"); log(`stale managed viewer (pid ${pid}) terminated`); } catch {}
    await new Promise((r) => setTimeout(r, 500));
    if (!listener().length && !(await probeViewer(port))) return true;
  }
  log(`viewer startup blocked on ${port}: existing listener is unverified, newer, or could not be stopped`);
  return false;
}

function initializeStartup(ctx, config) {
  const port = viewerPort(config?.viewer);
  if (config?.viewer && !port) log("viewer disabled: expected an integer port from 1 to 65535");
  const memoryDir = path.resolve(MEM_DIR);
  const version = pkgVersion();
  const remoteDisabled = config?.allowRemote === false || process.env.LM_REMOTE_DISABLED === "1";
  const want = { version, startupKey: createHash("sha256").update(JSON.stringify([version, memoryDir, remoteDisabled])).digest("hex") };
  try {
    // DSH 0.2.2: this exact route uses the authenticated owner-only /api bridge,
    // including Desktop's dsh-app://app carrier. No memory or directory is proxied.
    ctx.inject?.(["connection"], (host) => host.connection.fetch?.register({
      path: "/api/lm-memory-viewer",
      methods: ["GET"],
      requestBody: "buffered",
      fetch: async () => {
        const remote = port ? await probeViewer(port) : null;
        const status = !port ? "disabled" : !remote ? "offline" : matchesViewer(remote, want) ? "ready" : "stale";
        return Response.json({ port, status }, { headers: { "Cache-Control": "no-store" } });
      },
    }));
  } catch (error) { log(`viewer address bridge unavailable: ${error?.message ?? error}`); }
  const shimPath = writeServerShim(config);
  const node = resolveNode({ log });
  if (!node) return;
  if (shimPath) {
    // The DSH MCP row waits for this service, including when a shim cannot be written.
    try { ctx.provide?.("lmMemoryStartup", { node, shimPath, memoryDir }); }
    catch (error) { log(`MCP startup registration error: ${error?.message ?? error}`); }
  }
  if (!port) return;
  const viewerPath = ["../../server/viewer.mjs", "../../../server/viewer.mjs"]
    .map((r) => path.join(libDir(), r)).find((p) => fs.existsSync(p));
  if (!viewerPath) { log("viewer skipped: viewer.mjs not found"); return; }
  void ensureFreshViewer(port, node, viewerPath, want).then((shouldStart) => {
    if (shouldStart) spawnViewer(node, viewerPath, port, {
      ...process.env, LM_MEMORY_DIR: memoryDir, LM_VIEWER_STARTUP_KEY: want.startupKey,
      ...(remoteDisabled ? { LM_REMOTE_DISABLED: "1" } : {}),
    }, log);
  }).catch((error) => log(`viewer ensure error: ${error?.message ?? error}`));
}

function dispatchExtraction(session, texts, config) {
  try {
    // v0.15 allowRemote 开关：false 时完全不外呼 LLM（本地模式，只保留会话索引卡），默认 true
    if (config?.extract === false || config?.allowRemote === false || texts.length < 2) return true;
    const jobsDir = path.join(MEM_DIR, "extraction-jobs");
    fs.mkdirSync(jobsDir, { recursive: true });
    // v0.16 文件名带 rev（第七轮外审实锤竞态：文件名固定为 sessionId 时，续聊的新 dispatch 覆盖同一路径，
    // 旧 worker（仍在跑几十秒 LLM）完成时 rmSync 删掉的是【新任务】）——rev 入名 = 每次派发独立文件，互不覆盖。
    // v0.16.1：rev 含冒号/点号，Windows 文件名非法 → 清洗为安全字符。
    const rev = new Date().toISOString();
    const jobFile = path.join(jobsDir, `${session.id}-${rev.replace(/[:.]/g, "-")}.json`);
    fs.writeFileSync(jobFile, JSON.stringify({
      sessionId: session.id,
      rev, // v0.15.3 来源 revision：job 创建时固定——重跑同 job 复用同一 rev，
      // 候选 eid 与版本序都从它派生（复核实锤：helper 每次跑换新身份+刷新时间，旧 job 重跑会退回新摘要）
      date: new Date().toLocaleDateString("sv"),
      cwd: session.header?.cwd ?? "",
      texts,
      llm: typeof config?.llm === "object" ? config.llm : {}, // {model, baseURL, apiKeyEnv} 显式配置优先
      sessionModel: extractSessionModel(session) || undefined, // 会话真实模型（request/header），未显式配置时跟随
    })); // 写 job 文件（rev 入名，见上）
    // v0.16.2 任务协议（第九轮复核实锤：插件直接 spawn 绕过登记/领取，双 worker 出现在首次执行）：
    // 插件只写「待派发通知」，server 消费通知后执行「登记→原子领取→spawn」，与恢复器完全同一入口。
    appendQueue(path.join(MEM_DIR, "pending-jobs.jsonl"), { sessionId: session.id, rev, jobFile: path.basename(jobFile) });
    log(`extraction dispatched: ${session.id} (${texts.length} msgs)`);
    return true;
  } catch (e) {
    log(`extract dispatch error: ${e?.message ?? e}`);
    return false;
  }
}

function capture(session, config) {
  try {
    const rawTexts = extractUserTexts(session);
    if (!rawTexts || !session?.id) return;
    // v0.15 外发前防线：脱敏/剔除发生在任何落盘（会话卡首末句、提炼 job）之前——
    // 修复外审实锤「原始文本先写 job/pending，SECRET 检查来不及」。
    const { texts, dropped, redacted } = filterTextsForLLM(rawTexts, (op, d) => log(`${op} ${JSON.stringify(d)}`));
    if (dropped || redacted) log(`filtered before persist: ${dropped} dropped, ${redacted} redacted`);
    if (!texts.length) return;
    const hash = textHash(texts);
    if (alreadyCaptured(session.id, hash)) return;
    const min = Number.isFinite(config?.minUserMessages) ? config.minUserMessages : 2;
    if (texts.length < min) return;
    const cwd = session.header?.cwd ?? session.meta?.cwd ?? "";
    const date = new Date().toLocaleDateString("sv"); // v0.16 本地时区日期（第七轮外审实锤：UTC 截断使凌晨写入的日期回退一天）
    const first = texts[0].replace(/\s+/g, " ").slice(0, 120);
    const last = texts[texts.length - 1].replace(/\s+/g, " ").slice(0, 80);
    const rec = {
      sessionId: session.id,
      kind: "episode",
      content: `会话 ${date}｜${cwd || "未知目录"}｜${texts.length} 条用户输入｜首问「${first}」｜末问「${last}」`,
      tags: "auto-capture",
      eventDate: date,
      capturedAt: new Date().toISOString(),
    };
    fs.mkdirSync(MEM_DIR, { recursive: true });
    appendQueue(PENDING, rec);
    if (dispatchExtraction(session, texts, config)) markCaptured(session.id, hash);
    log(`captured ${session.id} (${texts.length} user msgs)`);
  } catch (e) {
    log(`capture error: ${e?.message ?? e}`);
  }
}

// ===== lm-refresh（v0.10）：记忆变更实时推送给「已开会话」 =====
// 病灶：会话只在启动时读一次记忆快照（current.md），之后记忆库的更新对它不可见，
// 旧会话要碰壁才发现新流程。解法：agent/pre-step 瀑布管道里检查 changes.jsonl
// （server 侧 announce() 追加的变更热流），有新记忆就往本 step 的消息列表尾部
// 注入一条 user 消息（source.kind=lm-memory-refresh，同 time-context 形状），
// 模型在下一步立刻看到——持续记忆流 + 场景触发（前瞻记忆）的最小实现。
// 纪律：异常静默不抛宿主；per-session 字节 offset 幂等；无变更零成本（一次 stat）。
const changesPath = () => path.join(MEM_DIR, "changes.jsonl");
const refreshOffsets = new Map(); // sessionId -> 已消费字节 offset（首次 pre-step 建基线=当时文件尾）
const seenEventIds = new Map(); // sessionId -> Set<eid>（v0.15.2：至少一次投递下跨 offset 重发的同一事件只应用一次）
const INJECT_OPS = new Set(["remember", "correct", "forget", "pin", "unpin", "wake"]);
const OP_LABEL = { remember: "新增", correct: "修正", forget: "删除", pin: "置顶", unpin: "取消置顶", wake: "唤醒" };
const KIND_LABEL = { preference: "偏好", fact: "事实", procedure: "经验", todo: "待办", episode: "会话" };

function readNewChanges(offset) {
  const file = changesPath();
  let st;
  try { st = fs.statSync(file); } catch { return { changes: [], newOffset: offset }; }
  let from = offset;
  if (st.size < from) from = 0; // 文件被清理/轮转 → 重头读
  if (st.size <= from) return { changes: [], newOffset: from };
  const buf = Buffer.alloc(st.size - from);
  const fd = fs.openSync(file, "r");
  try { fs.readSync(fd, buf, 0, buf.length, from); } finally { fs.closeSync(fd); }
  const text = buf.toString("utf8");
  const changes = [];
  let consumed = 0;
  const lines = text.split("\n");
  const complete = lines.slice(0, -1); // 末行可能半截（写方正在追加），不消费
  for (const line of complete) {
    consumed += Buffer.byteLength(line, "utf8") + 1;
    if (!line.trim()) continue;
    try { changes.push(JSON.parse(line)); } catch {}
  }
  return { changes, newOffset: from + consumed };
}

function buildDeltaText(changes) {
  const injectable = changes.filter((c) => INJECT_OPS.has(c.op));
  const dormantIds = changes.flatMap((c) => (c.op === "dormant" && Array.isArray(c.ids) ? c.ids : []));
  if (!injectable.length && !dormantIds.length) return null;
  const hhmm = (ts) => { try { const d = new Date(ts); return isNaN(d) ? String(ts).slice(11, 16) : d.toTimeString().slice(0, 5); } catch { return ts; } };
  const clip = (s, n) => { s = String(s ?? ""); return s.length > n ? s.slice(0, n) + "…" : s; };
  const lines = injectable.slice(0, 8).map((c) => {
    const idpart = c.new_id ?? c.id;
    return `- [${hhmm(c.ts)} ${OP_LABEL[c.op] ?? c.op}]${c.kind ? `[${KIND_LABEL[c.kind] ?? c.kind}] ` : " "}${clip(c.content, 160)}${idpart != null ? `（id=${idpart}${c.version ? ` v${c.version}` : ""}）` : ""}${c.reason ? `｜原因：${clip(c.reason, 60)}` : ""}`;
  });
  let out = "【记忆库实时更新】本会话运行期间，记忆库写入了以下变更（晚于本会话启动时加载的记忆快照）：";
  if (lines.length) out += "\n" + lines.join("\n");
  if (injectable.length > 8) out += `\n- …另有 ${injectable.length - 8} 条变更（memory_list 可查全量）`;
  if (dormantIds.length) out += `\n- 另有 ${dormantIds.length} 条长期未召回的记忆转入休眠（默认召回不包含；scope=dormant 可查）。`;
  out += "\n与当前任务相关的（尤其流程/坑/铁律类）一律以最新内容为准，需要全文调 memory_recall；标记「删除」的条目不要再引用；无关则忽略本条。";
  return boundedIndex(out, 8192, 40);
}

function refreshHook(config) {
  return async (payload, next) => {
    const decision = await next();
    try {
      if (!decision || decision.kind === "reject" || payload?.signal?.aborted) return decision;
      if (config?.refresh === false) return decision;
      const sid = payload?.agent?.session?.id ?? payload?.agent?.id;
      if (!sid) return decision;
      let st;
      try { st = fs.statSync(changesPath()); } catch { return decision; } // 无热流文件=尚无变更
      let offset = refreshOffsets.get(sid);
      if (offset === undefined) { refreshOffsets.set(sid, st.size); return decision; } // 本会话基线：此前的不算"新"
      const { changes, newOffset } = readNewChanges(offset);
      refreshOffsets.set(sid, newOffset); // 无论是否注入都推进，防重复注入死循环
      // v0.15.3：稳定事件身份去重——单次遍历内「检查即登记」，同批重复 eid 与跨 offset 重发都只应用一次
      // （复核实锤：先过滤整批再统一登记，批内两条相同 eid 会漏网注入两次）
      let seen = seenEventIds.get(sid);
      if (!seen) { seen = new Set(); seenEventIds.set(sid, seen); }
      const fresh = [];
      for (const c of changes) {
        if (!c.eid || !seen.has(c.eid)) { fresh.push(c); if (c.eid) seen.add(c.eid); }
      }
      const text = fresh.length ? buildDeltaText(fresh) : null;
      if (!text) return decision;
      log(`refresh push to session ${String(sid).slice(0, 8)}…: ${changes.length} changes`);
      return {
        ...decision,
        messages: [...decision.messages, {
          role: "user",
          id: randomUUID(),
          content: [{ type: "text", text }],
          source: { kind: "lm-memory-refresh", form: "snapshot", sections: [{ name: "lm-memory-refresh", text }] },
        }],
      };
    } catch (e) { log(`refresh error: ${e?.message ?? e}`); return decision; }
  };
}

export default function apply(ctx, config) {
  try {
    if (config?.memoryDir) { MEM_DIR = String(config.memoryDir); resolvePaths(); }
    try { initializeStartup(ctx, config); }
    catch (error) { log(`startup error: ${error?.message ?? error}`); }
    // 悬浮按钮已移除：设置 → 记忆库 是正式入口（用户反馈悬浮球多余）
    const sessions = new Map();
    const byId = (sessionId) => {
      try { return ctx.sessions?.get?.(sessionId) ?? sessions.get(sessionId) ?? null; } catch { return sessions.get(sessionId) ?? null; }
    };
    const track = (session) => {
      if (!session?.id) return;
      sessions.set(session.id, session);
      if (globalThis.__lmCaptureSessions) globalThis.__lmCaptureSessions.add(session);
    };
    globalThis.__lmCaptureSessions ??= new Set();
    globalThis.__lmCaptureConfig ??= config;
    ctx.on("session/created", (session) => { track(session); log(`event: session/created ${session?.id}`); });
    ctx.on("workspace/session-stop", ({ sessionId } = {}) => {
      log(`event: workspace/session-stop ${sessionId}`);
      const session = sessionId ? byId(sessionId) : null;
      if (session) capture(session, config);
    });
    ctx.on("session/disposed", (session) => {
      log(`event: session/disposed ${session?.id}`);
      try { refreshOffsets.delete(session?.id); } catch {}
      try { seenEventIds.delete(session?.id); } catch {}
      capture(session, config);
    });
    // lm-refresh：每个 step 前检查记忆变更热流，有新记忆就注入 delta（config.refresh=false 关闭）
    ctx.on("agent/pre-step", refreshHook(config));
    const taskRecallHook = createTaskRecallHook(config, MEM_DIR);
    if (taskRecallHook) ctx.on("agent/pre-step", taskRecallHook);
    // headless/一次性进程：进程退出时同步落盘（桌面常驻进程下由上面的实时事件覆盖）
    if (!globalThis.__lmCaptureExitHooked) {
      globalThis.__lmCaptureExitHooked = true;
      process.on("exit", () => {
        try {
          for (const session of globalThis.__lmCaptureSessions) capture(session, globalThis.__lmCaptureConfig);
        } catch {}
      });
    }
    log("plugin loaded");
  } catch (e) {
    log(`apply error: ${e?.message ?? e}`);
  }
}
