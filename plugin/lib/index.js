// dsh-lm-capture v0.1 — cordis 纯函数插件，零依赖。
// 监听 workspace/session-stop 与 session/disposed，把会话里「真实用户输入」
// （source.kind === 'user'，排除 runtime-context 等注入）提炼成一条 episode，
// 追加到 ~/.dsh/memory/pending-episodes.jsonl；由 lm-memory MCP server 在启动/召回时入库。
// 纪律：任何异常都不得抛出宿主进程；只写 stderr；幂等（同一 session 只采一次）。
import fs from "node:fs";
import { spawn, execFileSync } from "node:child_process";
import { randomUUID } from "node:crypto";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const libDir = () => path.dirname(fileURLToPath(import.meta.url));

let MEM_DIR = process.env.LM_MEMORY_DIR || path.join(os.homedir(), ".lm-memory");
const PENDING = path.join(MEM_DIR, "pending-episodes.jsonl");
const MARKER = path.join(MEM_DIR, "captured-sessions.jsonl");
const seen = new Set();

const log = (msg) => { try { console.error(`[lm-capture] ${msg}`); } catch {} };

function alreadyCaptured(sessionId) {
  if (seen.has(sessionId)) return true;
  try {
    return fs.existsSync(MARKER) && fs.readFileSync(MARKER, "utf8").includes(sessionId);
  } catch { return false; }
}
function markCaptured(sessionId) {
  seen.add(sessionId);
  try { fs.appendFileSync(MARKER, JSON.stringify({ ts: new Date().toISOString(), sessionId }) + "\n"); } catch {}
}

function extractSessionModel(session) {
  // 会话真实模型跟随：取最后一条 request/header 的 provider+model（会话中途换模型则以期末为准）
  try {
    let last = null;
    for (const e of session.ownEvents()) {
      if (e?.type === "request/header") last = e?.data?.header?.config ?? null;
    }
    return last && last.provider && last.model ? { provider: last.provider, model: last.model } : null;
  } catch { return null; }
}
function extractUserTexts(session) {
  let events;
  try { events = session.ownEvents(); } catch (e) { log(`ownEvents failed: ${e.message}`); return null; }
  const texts = [];
  for (const e of events) {
    if (e?.type !== "user/message") continue;
    if (e?.data?.source?.kind !== "user") continue; // 排除 runtime-context / time-context 等注入
    const text = (e.data.content || []).filter((c) => c?.type === "text").map((c) => c.text).join(" ").trim();
    if (text.length >= 2) texts.push(text);
  }
  return texts;
}

function resolveNode() {
  // 注意：DSH 自带的 runtime/bin/node 是壳脚本，依赖 DSH_DESKTOP_NODE_EXECUTABLE
  // 环境变量，宿主进程 env 里没有 → exec 空命令秒死。必须用真 node。
  const candidates = [
    process.env.DSH_NODE,
    "/opt/homebrew/bin/node",        // macOS homebrew
    "/usr/local/bin/node",           // macOS 手装
    "C:\\Program Files\\nodejs\\node.exe", // Windows 默认安装位
  ].filter(Boolean);
  if (process.execPath && /[\\/]node(\.exe)?$/.test(process.execPath)) return process.execPath; // 兼容正/反斜杠
  for (const c of candidates) { try { if (fs.existsSync(c)) return c; } catch {} }
  return "node";
}

function writeServerShim() {
  try {
    const realServer = ["../../server/memory-server.mjs", "../../../server/memory-server.mjs"]
      .map((r) => path.join(libDir(), r)).find((p) => fs.existsSync(p));
    if (!realServer) return;
    const binDir = path.join(MEM_DIR, "bin");
    fs.mkdirSync(binDir, { recursive: true });
    const shimPath = path.join(binDir, "lm-memory-server.mjs");
    const content = [
      "#!/usr/bin/env node",
      "// Auto-generated by dsh-lm-memory plugin — rewritten at every host start. Do not edit.",
      "// 稳定启动器：MCP 配置指向本文件（路径只依赖 HOME，GUI 宿主也成立）；",
      "// 真实服务器路径由插件按自身安装位置写入，规避缺 DSH_PROFILE_DIR/DSH_PROFILE",
      "// 环境变量时回退 profiles/default 的 spawn ENOENT → MCP 永久断连问题。",
      'import { pathToFileURL } from "node:url";',
      `await import(pathToFileURL(${JSON.stringify(realServer)}).href);`,
      "",
    ].join("\n");
    fs.writeFileSync(shimPath, content);
    log("server shim written: " + shimPath);
  } catch (e) { log("shim write error: " + (e?.message ?? e)); }
}

// ===== viewer 旧版自动升级（v0.10）=====
// 病灶：viewer 是 detached 进程，DSH app 重启杀不掉它；旧 viewer 占着端口且它 spawn 的
// MCP server 子进程也是旧代码（无 announce）→ 管理页写操作永远不进变更热流。
// 解法：探测 /api/version——缺端点或版本号 < 当前包版本 → 找到 pid（端点返回或 lsof 兜底）
// → SIGTERM → 拉起新 viewer。find/sleep 用 execFileSync 避免 async 噪音；一切异常静默。
const execFileSyncSafe = (cmd, args) => { try { return execFileSync(cmd, args, { encoding: "utf8", timeout: 3000 }).trim(); } catch { return ""; } };
function pkgVersion() {
  try { return JSON.parse(fs.readFileSync(path.join(libDir(), "../../package.json"), "utf8")).version || "0.0.0"; } catch { return "0.0.0"; }
}
function cmpVersion(a, b) {
  const pa = String(a).split(".").map(Number), pb = String(b).split(".").map(Number);
  for (let i = 0; i < 3; i++) { const d = (pa[i] || 0) - (pb[i] || 0); if (d) return d < 0 ? -1 : 1; }
  return 0;
}
async function ensureFreshViewer(port) {
  const url = "http://127.0.0.1:" + port;
  let remote = null;
  try {
    const r = await fetch(url + "/api/version", { signal: AbortSignal.timeout(1500) });
    if (r.ok) remote = await r.json();
  } catch {}
  const want = pkgVersion();
  if (remote && typeof remote.version === "string" && cmpVersion(remote.version, want) >= 0) return; // 已是新版，不动
  // 旧版/无端点 → 找 pid：优先端点返回，lsof 兜底（首次升级时旧 viewer 没有端点）
  let pid = Number(remote?.pid) || 0;
  if (!pid) {
    const out = execFileSyncSafe("lsof", ["-ti", ":" + port, "-sTCP:LISTEN"]).split("\n").map(Number).filter((n) => n > 1);
    pid = out[0] || 0;
  }
  if (pid > 1) {
    const cmdline = execFileSyncSafe("ps", ["-p", String(pid), "-o", "command="]);
    if (/viewer\.mjs/.test(cmdline)) {
      try { process.kill(pid, "SIGTERM"); log(`old viewer (pid ${pid}) terminated, respawning…`); } catch {}
      await new Promise((r) => setTimeout(r, 500));
    }
  }
}

function dispatchExtraction(session, texts, config) {
  try {
    if (config?.extract === false || texts.length < 2) return;
    const jobsDir = path.join(MEM_DIR, "extraction-jobs");
    fs.mkdirSync(jobsDir, { recursive: true });
    const jobFile = path.join(jobsDir, `${session.id}.json`);
    fs.writeFileSync(jobFile, JSON.stringify({
      sessionId: session.id,
      date: new Date().toISOString().slice(0, 10),
      cwd: session.header?.cwd ?? "",
      texts,
      llm: typeof config?.llm === "object" ? config.llm : {}, // {model, baseURL, apiKeyEnv} 显式配置优先
      sessionModel: extractSessionModel(session) || undefined, // 会话真实模型（request/header），未显式配置时跟随
    }));
        const child = spawn(resolveNode(), [path.join(libDir(), "extract-helper.mjs"), jobFile], {
      detached: true, stdio: "ignore",
      env: { ...process.env, LM_MEMORY_DIR: MEM_DIR },
    });
    child.unref();
    log(`extraction dispatched: ${session.id} (${texts.length} msgs)`);
  } catch (e) {
    log(`extract dispatch error: ${e?.message ?? e}`);
  }
}

function capture(session, config) {
  try {
    if (!session?.id || alreadyCaptured(session.id)) return;
    const texts = extractUserTexts(session);
    if (!texts) return;
    const min = Number.isFinite(config?.minUserMessages) ? config.minUserMessages : 2;
    if (texts.length < min) return;
    const cwd = session.header?.cwd ?? session.meta?.cwd ?? "";
    const date = new Date().toISOString().slice(0, 10);
    const first = texts[0].replace(/\s+/g, " ").slice(0, 120);
    const last = texts[texts.length - 1].replace(/\s+/g, " ").slice(0, 80);
    const rec = {
      sessionId: session.id,
      kind: "episode",
      content: `会话 ${date}｜${cwd || "未知目录"}｜${texts.length} 条用户输入｜首问「${first}」｜末问「${last}」`,
      tags: "auto-capture",
      capturedAt: new Date().toISOString(),
    };
    fs.mkdirSync(MEM_DIR, { recursive: true });
    fs.appendFileSync(PENDING, JSON.stringify(rec) + "\n");
    markCaptured(session.id);
    log(`captured ${session.id} (${texts.length} user msgs)`);
    dispatchExtraction(session, texts, config);
  } catch (e) {
    log(`capture error: ${e?.message ?? e}`);
  }
}

// ===== lm-refresh（v0.10）：记忆变更实时推送给「已开会话」 =====
// 病灶：会话只在启动时读一次记忆快照（current.md），之后记忆库的更新对它不可见，
// 旧会话要碰壁才发现新流程。解法：agent/pre-step 瀑布管道里检查 changes.jsonl
// （server 侧 announce() 追加的变更热流），有新记忆就往本 step 的消息列表尾部
// 注入一条 user 消息（source.kind=lm-memory-refresh，同 time-context 形状），
// 模型在下一步立刻看到——持续记忆流 + 场景触发（前瞻记忆）的最小实现。
// 纪律：异常静默不抛宿主；per-session 字节 offset 幂等；无变更零成本（一次 stat）。
const changesPath = () => path.join(MEM_DIR, "changes.jsonl");
const refreshOffsets = new Map(); // sessionId -> 已消费字节 offset（首次 pre-step 建基线=当时文件尾）
const INJECT_OPS = new Set(["remember", "correct", "forget", "pin", "unpin", "wake"]);
const OP_LABEL = { remember: "新增", correct: "修正", forget: "删除", pin: "置顶", unpin: "取消置顶", wake: "唤醒" };
const KIND_LABEL = { preference: "偏好", fact: "事实", procedure: "经验", todo: "待办", episode: "会话" };

function readNewChanges(offset) {
  const file = changesPath();
  let st;
  try { st = fs.statSync(file); } catch { return { changes: [], newOffset: offset }; }
  let from = offset;
  if (st.size < from) from = 0; // 文件被清理/轮转 → 重头读
  if (st.size <= from) return { changes: [], newOffset: from };
  const buf = Buffer.alloc(st.size - from);
  const fd = fs.openSync(file, "r");
  try { fs.readSync(fd, buf, 0, buf.length, from); } finally { fs.closeSync(fd); }
  const text = buf.toString("utf8");
  const changes = [];
  let consumed = 0;
  const lines = text.split("\n");
  const complete = lines.slice(0, -1); // 末行可能半截（写方正在追加），不消费
  for (const line of complete) {
    consumed += Buffer.byteLength(line, "utf8") + 1;
    if (!line.trim()) continue;
    try { changes.push(JSON.parse(line)); } catch {}
  }
  return { changes, newOffset: from + consumed };
}

function buildDeltaText(changes) {
  const injectable = changes.filter((c) => INJECT_OPS.has(c.op));
  const dormantIds = changes.flatMap((c) => (c.op === "dormant" && Array.isArray(c.ids) ? c.ids : []));
  if (!injectable.length && !dormantIds.length) return null;
  const hhmm = (ts) => { try { const d = new Date(ts); return isNaN(d) ? String(ts).slice(11, 16) : d.toTimeString().slice(0, 5); } catch { return ts; } };
  const clip = (s, n) => { s = String(s ?? ""); return s.length > n ? s.slice(0, n) + "…" : s; };
  const lines = injectable.slice(0, 8).map((c) => {
    const idpart = c.new_id ?? c.id;
    return `- [${hhmm(c.ts)} ${OP_LABEL[c.op] ?? c.op}]${c.kind ? `[${KIND_LABEL[c.kind] ?? c.kind}] ` : " "}${clip(c.content, 160)}${idpart != null ? `（id=${idpart}${c.version ? ` v${c.version}` : ""}）` : ""}${c.reason ? `｜原因：${clip(c.reason, 60)}` : ""}`;
  });
  let out = "【记忆库实时更新】本会话运行期间，记忆库写入了以下变更（晚于本会话启动时加载的记忆快照）：";
  if (lines.length) out += "\n" + lines.join("\n");
  if (injectable.length > 8) out += `\n- …另有 ${injectable.length - 8} 条变更（memory_list 可查全量）`;
  if (dormantIds.length) out += `\n- 另有 ${dormantIds.length} 条长期未召回的记忆转入休眠（不再参与召回）。`;
  out += "\n与当前任务相关的（尤其流程/坑/铁律类）一律以最新内容为准，需要全文调 memory_recall；标记「删除」的条目不要再引用；无关则忽略本条。";
  return out;
}

function refreshHook(config) {
  return async (payload, next) => {
    const decision = await next();
    try {
      if (!decision || decision.kind === "reject" || payload?.signal?.aborted) return decision;
      if (config?.refresh === false) return decision;
      const sid = payload?.agent?.session?.id ?? payload?.agent?.id;
      if (!sid) return decision;
      let st;
      try { st = fs.statSync(changesPath()); } catch { return decision; } // 无热流文件=尚无变更
      let offset = refreshOffsets.get(sid);
      if (offset === undefined) { refreshOffsets.set(sid, st.size); return decision; } // 本会话基线：此前的不算"新"
      const { changes, newOffset } = readNewChanges(offset);
      refreshOffsets.set(sid, newOffset); // 无论是否注入都推进，防重复注入死循环
      const text = changes.length ? buildDeltaText(changes) : null;
      if (!text) return decision;
      log(`refresh push to session ${String(sid).slice(0, 8)}…: ${changes.length} changes`);
      return {
        ...decision,
        messages: [...decision.messages, {
          role: "user",
          id: randomUUID(),
          content: [{ type: "text", text }],
          source: { kind: "lm-memory-refresh", form: "snapshot", sections: [{ name: "lm-memory-refresh", text }] },
        }],
      };
    } catch (e) { log(`refresh error: ${e?.message ?? e}`); return decision; }
  };
}

export default function apply(ctx, config) {
  try {
    if (config?.memoryDir) MEM_DIR = String(config.memoryDir);
    // MCP 稳定启动器：每次宿主启动重写，路径只依赖 HOME（见 writeServerShim 注释）
    writeServerShim();
    // viewer 自启（config.viewer = 端口号）：先探测/升级旧版 viewer（v0.10），再确保有活的最新版
    if (config?.viewer) {
      const port = Number(config.viewer);
      void ensureFreshViewer(port).then(async () => {
        let alive = false;
        try {
          const r = await fetch("http://127.0.0.1:" + port + "/api/version", { signal: AbortSignal.timeout(1500) });
          alive = r.ok; // 只有新版 viewer 才有此端点
        } catch {}
        if (alive) { log("viewer already fresh on " + port); return; }
        // 包形态：plugin/lib → ../../server；旧手工部署：plugin/dsh-lm-capture/lib → ../../../server
        const viewerPath = ["../../server/viewer.mjs", "../../../server/viewer.mjs"]
          .map((r) => path.join(libDir(), r)).find((p) => fs.existsSync(p));
        if (viewerPath) {
          const ch = spawn(resolveNode(), [viewerPath, String(port)], { detached: true, stdio: "ignore", env: { ...process.env, LM_MEMORY_DIR: MEM_DIR } });
          ch.unref();
          log("viewer spawned on " + port);
        }
      }).catch((e) => log("viewer ensure error: " + (e?.message ?? e)));
    }
    // 悬浮按钮已移除：设置 → 记忆库 是正式入口（用户反馈悬浮球多余）
    const sessions = new Map();
    const byId = (sessionId) => {
      try { return ctx.sessions?.get?.(sessionId) ?? sessions.get(sessionId) ?? null; } catch { return sessions.get(sessionId) ?? null; }
    };
    const track = (session) => {
      if (!session?.id) return;
      sessions.set(session.id, session);
      if (globalThis.__lmCaptureSessions) globalThis.__lmCaptureSessions.add(session);
    };
    globalThis.__lmCaptureSessions ??= new Set();
    globalThis.__lmCaptureConfig ??= config;
    ctx.on("session/created", (session) => { track(session); log(`event: session/created ${session?.id}`); });
    ctx.on("workspace/session-stop", ({ sessionId } = {}) => {
      log(`event: workspace/session-stop ${sessionId}`);
      const session = sessionId ? byId(sessionId) : null;
      if (session) capture(session, config);
    });
    ctx.on("session/disposed", (session) => {
      log(`event: session/disposed ${session?.id}`);
      try { refreshOffsets.delete(session?.id); } catch {}
      capture(session, config);
    });
    // lm-refresh：每个 step 前检查记忆变更热流，有新记忆就注入 delta（config.refresh=false 关闭）
    ctx.on("agent/pre-step", refreshHook(config));
    // headless/一次性进程：进程退出时同步落盘（桌面常驻进程下由上面的实时事件覆盖）
    if (!globalThis.__lmCaptureExitHooked) {
      globalThis.__lmCaptureExitHooked = true;
      process.on("exit", () => {
        try {
          for (const session of globalThis.__lmCaptureSessions) capture(session, globalThis.__lmCaptureConfig);
        } catch {}
      });
    }
    log("plugin loaded");
  } catch (e) {
    log(`apply error: ${e?.message ?? e}`);
  }
}
